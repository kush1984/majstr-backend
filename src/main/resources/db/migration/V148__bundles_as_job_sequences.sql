--     everyone: a master who FORKED one keeps his fork (the override row cascades away, the owned
--     copy stays), a master who HID one simply stops having nothing to hide, and no estimate points
--     at a template — its lines were copied by value.
--   * 30 are RENAMED in place rather than deleted and recreated, so a master's hide or fork
--     (`template_default_override.template_id`) follows the bundle he already acted on. 18 are new.
--   * 141 catalog positions are ADDED across the nine trades — every line a sequence needs and the
--     trade did not ship. A bundle line resolves its price off the master's OWN catalog by
--     lower(trim(name)) and a miss applies it at 0 ₴ SILENTLY (V112), so a position no catalog
--     carries cannot stand in a bundle. Where another trade already ships the same job, the row is
--     copied VERBATIM — name, unit, price and description — so a master running both trades owns
--     one row, not two (V116's rule), and the trade-less norms on those names apply at once.
--
-- The owner's six rulings on the open points (2026-10-07), all as recommended:
--   1. A DRYWALL construction bundle ends at the boards; the joint work comes from the Q1-Q4
--      finish-level bundle applied with it. That is what removes today's double putty when «Стеля з
--      гіпсокартону» and Q3 are applied together.
--   2. ONE wording for protection and debris in every trade: «Захист підлоги картоном», «Фасування
--      сміття в мішки», «Винесення та вивезення будівельного сміття», «Прибирання приміщення після
--      робіт». TILING's «Укриття плівкою…» and PAINTER's «Збирання сміття в мішки після демонтажу»
