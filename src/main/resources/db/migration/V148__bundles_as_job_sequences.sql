-- 6. SELF-CHECKS — about this migration's own work only.
-- -------------------------------------------------------------------------------------------------
DO $$
DECLARE
    v_count int;
    v_text  text;
BEGIN
    -- Every line of every bundle written here resolves to a position its own trade ships: the
    -- one failure this whole migration exists not to cause is a line applied at 0 ₴.
    SELECT count(*), string_agg(g.trade || ' | ' || g.name || ' | ' || i.name, '; ')
      INTO v_count, v_text
      FROM _v148_target g
      JOIN estimate_template_items i ON i.template_id = g.template_id
     WHERE NOT EXISTS (SELECT 1 FROM catalog_templates ct
                        WHERE ct.trade = g.trade
                          AND lower(trim(ct.name)) = lower(trim(i.name))
                          AND ct.type = i.type AND ct.unit = i.unit);
    IF v_count <> 0 THEN
        RAISE EXCEPTION 'V148: % bundle line(s) resolve to no catalog position (0 UAH on apply): %',
            v_count, v_text;
    END IF;

    -- Each bundle holds exactly the sequence declared for it, in that order.
    SELECT count(*) INTO v_count
      FROM _v148_target g
      JOIN _v148_line l ON l.trade = g.trade AND l.bundle = g.name
     WHERE NOT EXISTS (SELECT 1 FROM estimate_template_items i
                        WHERE i.template_id = g.template_id
                          AND i.name = l.name AND i.unit = l.unit AND i.sort_order = l.pos);
    IF v_count <> 0 THEN
        RAISE EXCEPTION 'V148: % declared bundle line(s) are missing or out of place', v_count;
    END IF;
    SELECT count(*) INTO v_count
      FROM _v148_target g
     WHERE (SELECT count(*) FROM estimate_template_items i WHERE i.template_id = g.template_id)
        <> (SELECT count(*) FROM _v148_line l WHERE l.trade = g.trade AND l.bundle = g.name);
    IF v_count <> 0 THEN
        RAISE EXCEPTION 'V148: % bundle(s) carry lines beyond their declared sequence', v_count;
    END IF;

    SELECT count(*) INTO v_count FROM _v148_bundle;
    IF (SELECT count(*) FROM _v148_target) <> v_count THEN
        RAISE EXCEPTION 'V148: % bundle(s) declared, % found as defaults',
            v_count, (SELECT count(*) FROM _v148_target);
    END IF;

    SELECT count(*) INTO v_count
      FROM estimate_templates t JOIN _v148_drop d ON d.trade = t.trade AND d.name = t.name
     WHERE t.owner_id IS NULL AND t.is_default;
    IF v_count <> 0 THEN
        RAISE EXCEPTION 'V148: % retired bundle(s) are still defaults', v_count;
    END IF;

    -- No bundle written here is a fragment. The finish levels are the one deliberate exception:
    -- they are applied ON TOP of a construction bundle and Q1 has four honest steps.
    SELECT count(*), string_agg(g.name, '; ') INTO v_count, v_text
      FROM _v148_target g
     WHERE g.name NOT LIKE 'Підготовка ГКЛ%'
       AND (SELECT count(*) FROM estimate_template_items i WHERE i.template_id = g.template_id) < 6;
    IF v_count <> 0 THEN
        RAISE EXCEPTION 'V148: % bundle(s) are shorter than six lines: %', v_count, v_text;
    END IF;

    -- The ceiling frame stopped buying wool, and the wool position buys it.
    IF EXISTS (SELECT 1 FROM material_norm n JOIN material m ON m.id = n.material_id
                WHERE n.owner_id IS NULL AND m.code = 'MINERAL_WOOL'
                  AND n.name_key = 'каркасна звукоізоляція (гкл в два слоя) стелі') THEN
        RAISE EXCEPTION 'V148: the shipped ceiling frame position still buys mineral wool';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM material_norm n JOIN material m ON m.id = n.material_id
                    WHERE n.owner_id IS NULL AND m.code = 'MINERAL_WOOL'
                      AND n.name_key = 'звукоізоляція стелі мінеральною ватою') THEN
        RAISE WARNING 'V148: the wall wool norm was not found, so the ceiling wool position buys nothing';
    END IF;

    -- V118's own invariants after the re-rank.
    SELECT count(*) INTO v_count FROM catalog_templates WHERE sort_order = 0;
    IF v_count > 0 THEN
        RAISE EXCEPTION 'V148: % templates were left unranked', v_count;
    END IF;
    SELECT count(*) INTO v_count FROM (
        SELECT sort_order FROM catalog_templates GROUP BY sort_order HAVING count(*) > 1) d;
    IF v_count > 0 THEN
        RAISE EXCEPTION 'V148: % template ranks are shared by more than one row', v_count;
    END IF;
END $$;
