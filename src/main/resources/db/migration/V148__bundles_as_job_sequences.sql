-- the master RUN the job — one stage after another, protection first and cleanup last — the catalog
-- dumps are split into a few real sequences, and NOTHING of two or three lines ships as a bundle.
--
-- What changes, by shape:
--
--   * 115 default bundles become 102. Every one that stays is REWRITTEN in place: its lines are
--     matched by name+unit and keep their ids (an offline replay naming a default's item id still
--     lands, V143), a line the new sequence drops is deleted, a missing one is inserted, and
--     `sort_order` — which IS the content (V112) — is rewritten whole.
--   * 31 are DELETED: the five catalog dumps the review named («ЕЛЕКТРИКА» 99, «САНТЕХНІКА» 104,
