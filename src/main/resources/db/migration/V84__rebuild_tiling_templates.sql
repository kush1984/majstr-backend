-- Tiling estimate templates, rebuilt on top of the V82 catalog.
--
-- The 13 that existed could not survive the rebuild anyway: they named positions by NAME, and
-- V82 replaced every tiling position, so each old bundle would have priced its lines at 0. They
-- also overlapped badly — «Ванна кімната», «Санвузол повний» and «Душова з піддоном» were three
-- names for largely the same list, and «Кухонний фартух» and «Фартух керамограніт» differed by
-- one position. A master choosing between three bundles that do the same thing learns nothing
-- from the choice.
--
-- What replaces them: 9 bundles for the jobs a tiler actually takes, 2 for the niches that are a
-- different trade in practice (pools/mosaic, natural stone), and «УСІ ПЛИТОЧНІ РОБОТИ» — the
-- renamed catch-all from V50, now holding all 167 positions so the master can tick off an unusual
-- job instead of hunting the catalog.
--
-- Four positions are repeated in every bundle: covering with film, rubbish removal, cleaning up,
-- and the warranty callout. A tiler bills these on nearly every job and a bundle that omits them
-- teaches the master to omit them too — which is money they earn and forget to charge for. They
-- are absent from «УСІ ПЛИТОЧНІ РОБОТИ» only because it already contains everything.
--
-- Bundle lines carry name + unit and NO quantity and NO price: quantities are per object, and
-- the price is substituted from the master's OWN catalog by name at apply-time
-- (EstimateTemplateService). So a master who repriced a position keeps their price here too.
--
-- ============ WHAT IS NEVER TOUCHED ============================================
--   1. Templates a master saved themselves (is_default = false). The DELETE below is fenced on
--      is_default, so «зберегти кошторис як шаблон» output is untouched.
--   2. estimate_items — no estimate built from an old bundle changes. A template is a starting
--      point that is copied, not a live link.
-- ==============================================================================
--
-- Every position name below is generated from the same JSON that produced V82 and validated
-- against it, because a bundle line that names a position the catalog does not have silently
-- prices at 0 — and it was exactly this class of mismatch that stopped startup in V71.

DELETE FROM estimate_templates WHERE is_default AND trade = 'TILING';

